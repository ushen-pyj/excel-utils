use crate::common::table::parse_table;
use crate::models::{PrintResult, TableInput};

pub fn build_report(input: TableInput, title: String) -> Result<PrintResult, String> {
    let table = parse_table(input)?;

    Ok(PrintResult {
        title,
        summary: vec![
            format!("Rows: {}", table.rows.len()),
            format!("Columns: {}", table.columns.len()),
            "Preview defaults to the first 20 rows".to_string(),
        ],
        columns: table.columns,
        rows: table.rows.into_iter().take(20).collect(),
        generated_at: "Generated by the Rust processing layer".to_string(),
    })
}
